//! Emit canonical generated schema; semantic refinements remain reviewed source.
//! `tools/check_contracts.py` compares the output to the checked-in artifact.
use schemars::{schema_for, JsonSchema};
use serde::Serialize;
use serde_json::{json, Value};
use vp_product_domain::*;

#[derive(Serialize, JsonSchema)]
#[serde(tag = "contract", content = "payload", rename_all = "snake_case")]
#[allow(dead_code)]
enum ContractRoot {
    NodeProfile(NodeProfile),
    ServerListener(ServerListener),
    ProductConfig(ProductConfig),
    RuntimeSnapshot(Box<RuntimeSnapshot>),
    RuntimeEvent(RuntimeEvent),
    ProductError(ProductError),
    BuildInfo(BuildInfo),
    CapabilityDescriptor(CapabilityDescriptor),
    PresetCatalog(PresetCatalog),
    SubscriptionSource(SubscriptionSource),
    SubscriptionStatus(SubscriptionStatus),
    ImportReport(ImportReport),
    ImportNodePreview(ImportNodePreview),
    OperationSummary(OperationSummary),
    ChangePlanSummary(ChangePlanSummary),
    DraftSummary(DraftSummary),
    ManagementSnapshot(ManagementSnapshot),
    CredentialInventory(CredentialInventory),
    CredentialCreate(CredentialCreatePayload),
    CredentialRetire(CredentialRetirePayload),
    PublicationSummary(PublicationSummary),
    PublicationCreate(PublicationCreatePayload),
    PublicationReplace(PublicationReplacePayload),
    PublicationIssue(PublicationIssuePayload),
    PublicationRevoke(PublicationRevokePayload),
    PublicationIssuedSecret(PublicationIssuedSecret),
    Request(CommandEnvelope<Value>),
    Result(ResultEnvelope<Value>),
}

// These generic root types are instantiated only with arbitrary JSON payloads;
// endpoint dispatch is responsible for strict method-specific payload decoding.
fn public_name(name: &str) -> &str {
    name.strip_suffix("_for_AnyValue").unwrap_or(name)
}
fn normalize(value: &mut Value) {
    match value {
        Value::Object(object) => {
            if let Some(Value::String(reference)) = object.get_mut("$ref") {
                if let Some(name) = reference.strip_prefix("#/definitions/") {
                    *reference = format!("#/$defs/{}", public_name(name));
                }
            }
            for child in object.values_mut() {
                normalize(child);
            }
        }
        Value::Array(values) => values.iter_mut().for_each(normalize),
        _ => {}
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let generated = serde_json::to_value(schema_for!(ContractRoot))?;
    let refinements: Value = serde_json::from_str(include_str!(
        "../../../contracts/schema/v1.refinements.json"
    ))?;
    let mut definitions = serde_json::Map::new();
    for (name, schema) in generated["definitions"]
        .as_object()
        .ok_or("missing generated definitions")?
    {
        let mut schema = schema.clone();
        normalize(&mut schema);
        definitions.insert(public_name(name).into(), schema);
    }
    for (name, refinement) in refinements["$defs"]
        .as_object()
        .ok_or("missing reviewed refinements")?
    {
        if let Some(schema) = definitions.get_mut(name) {
            // Intersection is deliberate: reviewed semantic bounds cannot erase
            // generated strict field names/types, and generation cannot silently
            // drop ID/secret/counter/security constraints from the baseline.
            let object = schema
                .as_object_mut()
                .ok_or("definition must be an object")?;
            object
                .entry("allOf")
                .or_insert_with(|| json!([]))
                .as_array_mut()
                .ok_or("allOf must be an array")?
                .push(refinement.clone());
        } else {
            definitions.insert(name.clone(), refinement.clone());
        }
    }
    let schema = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://vp.example.invalid/contracts/v1.schema.json",
        "title": "VP product contracts v1",
        "$comment": "GENERATED by vp-product-domain export_schema from Rust DTOs plus v1.refinements.json. Validate against a named definition. Cross-field Rust validation is additionally mandatory. Do not edit this artifact by hand.",
        "$defs": definitions,
    });
    println!("{}", serde_json::to_string_pretty(&schema)?);
    Ok(())
}
